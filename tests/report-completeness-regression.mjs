import assert from 'node:assert/strict';
import fs from 'node:fs';
import ExcelJS from 'exceljs';
import {validateTemplate} from '../lib/reportTemplate.mjs';
import {buildLandEvaluationExcelBuffer} from '../lib/landEvaluationExcel.js';
import {buildLandEvaluationPdfBuffer} from '../lib/landEvaluationPdf.mjs';
import {assessReportQuality} from '../lib/reportQuality.mjs';
const fixture=fs.readFileSync('tests/submit-report.mjs','utf8').match(/const completeReportText = `([\s\S]*?)`;/)[1];
const broken=fixture.replace('市場行情總結：待複核','案名｜類型｜成交行情\n甲案｜預售｜待複核\n市場行情總結：待複核');
assert.ok(validateTemplate(broken).some(x=>x.includes('不可用彙總文字表取代')));
const cases=['甲案','乙案','丙案'].map((name,i)=>`競案${i+1}｜${name}\n建設公司：${name}建設\n競案等級：附近比較\n案子規劃：兩房25坪、三房35坪\n屋齡：預售\n成交期間：2026-04-22至2026-10-22\n成交筆數：待複核，頁面不足不等於零成交\n成交價格：待複核\n車位類型：待複核\n車位價格：待複核\n資訊來源：測試資料2026-10-22\n參考價值：同生活圈產品比較`).join('\n\n');
const text=fixture.replace('市場行情總結：待複核',cases+'\n市場行情總結：甲案、乙案、丙案成交尚未核齊。');
assert.deepEqual(validateTemplate(text),[]);
const workbook=new ExcelJS.Workbook();await workbook.xlsx.load(await buildLandEvaluationExcelBuffer({report_text:text}));
assert.deepEqual([19,20,21].map(n=>workbook.worksheets[0].getCell('C'+n).value),['甲案','乙案','丙案']);
assert.equal(workbook.getWorksheet('成交統計').rowCount,25);
const empty=new ExcelJS.Workbook();await empty.xlsx.load(await buildLandEvaluationExcelBuffer({report_text:fixture}));
assert.match(String(empty.getWorksheet('成交統計').getCell('C2').value),/不是零成交/);
assert.ok(assessReportQuality({report_text:fixture.replace('建議成交價格：30萬／坪','建議成交價格：30萬／坪，僅壓力測試')}).missing_core_fields.some(x=>x.includes('試算假設')));
const pdf=await buildLandEvaluationPdfBuffer({report_text:text});assert.ok(pdf.length>1000);
const tall=text.replace('首購族｜自住｜總價｜兩房｜待複核','首購族｜'+ '家庭生活及通勤需求。'.repeat(180)+'｜總價｜兩房｜待複核');
assert.ok((await buildLandEvaluationPdfBuffer({report_text:tall})).length>pdf.length);
console.log('Report completeness regressions passed.');
