import assert from 'node:assert/strict';
import { summarizeTransactions } from '../lib/transactionStats.mjs';
const base = { projectId: 'p', recordId: 'r', unitId: 'A-2', status: 'valid', updatedAt: '2026-10-05', kind: 'presale', transactionDate: '2026-05-01', use: 'residential', floor: 2, specialTransaction: false, totalPrice: 11000000, parkingPrice: 1000000, areaSqm: 110, parkingAreaSqm: 10 };
const run = rows => summarizeTransactions({ projectId: 'p', rows, startMonth: '2026-04', endMonth: '2026-06' });
const result = run([base, base]);
assert.equal(result.valid, true);
assert.deepEqual(result.months, { '2026-04': 0, '2026-05': 1, '2026-06': 0 });
assert.equal(result.monthlyAverage, 1/3);
assert.ok(Math.abs(result.residentialPrices[0].priceWanPerPing - 33.05785) < 0.0001);
assert.equal(run([base,{ ...base, status:'cancelled', updatedAt:'2026-10-06' }]).effectiveSaleCount,0);
assert.equal(run([base,{ ...base, recordId:'delivery', kind:'first_sale', originalPresaleId:'r' }]).effectiveSaleCount,1);
assert.equal(run([{ ...base, projectId:'wrong' }]).valid,false);
assert.equal(run([base,{ ...base, recordId:'other' }]).valid,false);
assert.equal(run([{ ...base, parkingPrice:null }]).valid,false);
assert.equal(run([{ ...base, kind:'resale' }]).effectiveSaleCount,0);
assert.equal(run([{ ...base, floor:1 }]).residentialPrices.length,0);
assert.equal(run([base,{ ...base, totalPrice:12000000 }]).valid,false);
assert.equal(run([base]).inventory,null,'missing total units must not produce inventory');
assert.equal(run([base]).allowFormalPriceUse,false,'fewer than three price samples cannot support formal pricing');
assert.equal(run([null]).valid,false);
assert.equal(run([{ ...base, use: undefined }]).valid,false);
assert.equal(summarizeTransactions({ projectId:'p', rows:[{...base, transactionDate:'2026-02-31'}], startMonth:'2026-02', endMonth:'2026-03' }).valid,false);
const sufficient = run([base,{...base,recordId:'r2',unitId:'B-2'},{...base,recordId:'r3',unitId:'C-2'}]);
assert.equal(sufficient.priceSampleCountSufficient,true);
assert.equal(sufficient.allowFormalPriceUse,false,'correct calculation is not proof of source authenticity');
assert.equal(sufficient.requiresSourceReview,true);
console.log('Transaction corrections, cancellations, identity, delivery deduplication, prices and zero months passed.');
